# STORED CASE BY ID
# ==========================================================

@app.get(
    "/cases/{case_id}"
)
def stored_case(
    case_id: str
):

    try:

        all_cases = normalize_cases(
            get_all_cases()
        )

        for case in all_cases:

            if case.get("case_id") == case_id:
                return case

        raise HTTPException(
            status_code=404,
            detail=f"Case {case_id} was not found."
        )

    except HTTPException:
        raise

    except Exception as e:

        raise HTTPException(
            status_code=500,
            detail=(
                f"Case retrieval error: "
                f"{type(e).__name__}: {e}"
            )
        )


