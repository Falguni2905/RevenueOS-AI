def normalize_case(case):
    if not isinstance(case, dict):
        return {}

    normalized = dict(case)

    normalized.setdefault("review_id", None)
    normalized.setdefault("review_status", "N/A")
    normalized.setdefault("reviewer", None)
    normalized.setdefault("review_decision", None)
    normalized.setdefault("review_comments", None)
    normalized.setdefault("updated_at", normalized.get("created_at"))

    normalized["merchant_id"] = str(normalized.get("merchant_id", ""))
    normalized["case_id"] = str(normalized.get("case_id", ""))
    normalized["status"] = str(normalized.get("status", "UNKNOWN"))
    normalized["recommended_action"] = str(
        normalized.get("recommended_action", "UNKNOWN")
    )
    normalized["risk_category"] = str(
        normalized.get("risk_category", "Unknown")
    )

    try:
        normalized["risk_score"] = round(
            float(normalized.get("risk_score", 0)), 2
        )
    except (TypeError, ValueError):
        normalized["risk_score"] = 0.0

    try:
        normalized["confidence"] = float(
            normalized.get("confidence", 0)
        )
    except (TypeError, ValueError):
        normalized["confidence"] = 0.0

    return normalized


def normalize_cases(cases):
    return [
        normalize_case(case)
        for case in cases
        if isinstance(case, dict)
    ]


@app.get(
    "/cases"
)
def cases():

    try:

        all_cases = get_all_cases()
        normalized_cases = normalize_cases(all_cases)

        return {
            "count": len(normalized_cases),
            "cases": normalized_cases
        }

    except Exception as e:

        raise HTTPException(
            status_code=500,
            detail=(
                f"Case retrieval error: "
                f"{type(e).__name__}: {e}"
            )
        )


