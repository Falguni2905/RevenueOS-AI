# NORMALIZE AGENT RESULT
# ==========================================================

def normalize_result(
    result,
    merchant_id
):

    if result is None:

        return None

    if not isinstance(
        result,
        dict
    ):

        return {
            "merchant_id":
                merchant_id,

            "decision":
                "ERROR",

            "reason":
                "RevenueOS-AI returned an invalid result format."
        }


    if not result.get(
        "merchant_id"
    ):

        result["merchant_id"] = (
            merchant_id
        )


    if not result.get(
        "decision"
    ):

        result["decision"] = (
            "UNKNOWN"
        )


    reason = result.get(
        "reason"
    )


    if (
        reason is None
        or str(reason).strip() == ""
        or str(reason).strip().lower()
        in [
            "none",
            "no reason provided"
        ]
    ):

        result["reason"] = (
            generate_reason(result)
        )


    if "failure_rate" in result:

        try:

            result["failure_rate"] = float(
                result["failure_rate"]
            )

        except (
            TypeError,
            ValueError
        ):

            pass


    if "risk_score" in result:

        try:

            result["risk_score"] = round(
                float(
                    result["risk_score"]
                ),
                2
            )

        except (
            TypeError,
            ValueError
        ):

            pass


    return result


