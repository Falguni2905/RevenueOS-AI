# REASON FALLBACK
# ==========================================================

def generate_reason(result):

    decision = str(
        result.get("decision", "")
    ).strip().upper()

    risk_score = result.get(
        "risk_score",
        0
    )

    risk_category = result.get(
        "risk_category",
        "Unknown"
    )

    failure_rate = result.get(
        "failure_rate",
        0
    )

    try:

        risk_score = float(
            risk_score
        )

    except (
        TypeError,
        ValueError
    ):

        risk_score = 0.0

    try:

        failure_rate = float(
            failure_rate
        )

    except (
        TypeError,
        ValueError
    ):

        failure_rate = 0.0

    failure_rate_pct = (
        failure_rate * 100
    )


    if decision == "INVESTIGATE":

        if risk_score >= 90:

            return (
                "Very high merchant risk detected. "
                "Automated investigation is required "
                "to determine the underlying cause."
            )

        elif failure_rate_pct >= 5:

            return (
                "Elevated transaction failure behaviour "
                "detected. Merchant requires automated "
                "investigation."
            )

        elif risk_category.lower() == "high":

            return (
                "High merchant risk detected. "
                "Automated investigation is required."
            )

        return (
            "Merchant risk indicators require "
            "automated investigation."
        )


    if decision == "ESCALATE":

        return (
            "Critical merchant risk detected. "
            "Immediate human review and escalation "
            "are required."
        )


    if decision == "MONITOR":

        if failure_rate_pct >= 5:

            return (
                f"Merchant has a {failure_rate_pct:.2f}% "
                "transaction failure rate. Risk is not "
                "critical, but the elevated failure "
                "behaviour requires continuous monitoring."
            )

        if risk_score >= 30:

            return (
                f"Merchant has a risk score of "
                f"{risk_score:.2f} and is classified as "
                f"{risk_category}. Continuous monitoring "
                "is recommended."
            )

        return (
            "Merchant risk is moderate and does not "
            "currently require automated investigation. "
            "Continuous monitoring is recommended."
        )


    if decision == "NO_ACTION":

        return (
            "Merchant risk and transaction behaviour "
            "are within the normal operating range. "
            "No immediate action is required."
        )


    if decision == "ERROR":

        return (
            "The RevenueOS-AI agent encountered an error "
            "while processing this merchant."
        )


    if decision == "UNKNOWN":

        return (
            "The merchant could not be evaluated because "
            "the merchant record or decision was unavailable."
        )


    return (
        "Decision generated by RevenueOS-AI based on "
        "available merchant risk indicators."
    )


